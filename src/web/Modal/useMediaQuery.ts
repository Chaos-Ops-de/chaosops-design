import { useEffect, useState } from 'react';

/** SSR-safe matchMedia hook. Unsupported queries (older Safari/Firefox for
 * prefers-contrast/prefers-reduced-transparency) resolve to `false`, which is
 * the correct "don't change behavior" fallback for these features. */
export function useMediaQuery(query: string): boolean {
  const [matches, setMatches] = useState(() =>
    typeof window !== 'undefined' && 'matchMedia' in window ? window.matchMedia(query).matches : false,
  );

  useEffect(() => {
    if (typeof window === 'undefined' || !('matchMedia' in window)) return;
    const mql = window.matchMedia(query);
    const handler = (e: MediaQueryListEvent) => setMatches(e.matches);
    setMatches(mql.matches);
    mql.addEventListener('change', handler);
    return () => mql.removeEventListener('change', handler);
  }, [query]);

  return matches;
}
